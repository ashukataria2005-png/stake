export const LIMBO_CONFIG = {
  MIN_TARGET_MULTIPLIER: 1.01,
  MAX_TARGET_MULTIPLIER: 1000000.0,
  BASE_RTP_PERCENT: 99.0, // 1% House Edge
  MAX_WIN_CAP_MULTIPLIER: 1000000.0,
};

export function calculateLimboWinChance(targetMultiplier: number): number {
  const clamped = Math.max(
    LIMBO_CONFIG.MIN_TARGET_MULTIPLIER,
    Math.min(LIMBO_CONFIG.MAX_TARGET_MULTIPLIER, targetMultiplier)
  );
  return parseFloat((LIMBO_CONFIG.BASE_RTP_PERCENT / clamped).toFixed(4));
}

// ============================================================================
// 4. DICE FORMULAS & HOUSE EDGE
// ============================================================================
export const DICE_CONFIG = {
  MIN_TARGET: 0.01,
  MAX_TARGET: 99.98,
  HOUSE_EDGE_PERCENT: 1.0,
  RTP_PERCENT: 99.0,
};

export function calculateDiceMultiplier(winChance: number): number {
  if (winChance <= 0) return 99.0;
  return parseFloat((DICE_CONFIG.RTP_PERCENT / winChance).toFixed(4));
}

export function calculateDiceWinChance(target: number, isRollOver: boolean): number {
  return isRollOver
    ? parseFloat((100.0 - target).toFixed(4))
    : parseFloat(target.toFixed(4));
}

