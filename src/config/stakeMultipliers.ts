export const MINES_MULTIPLIERS_MATRIX: Record<number, number[]> = Object.fromEntries(
  Object.entries(STAKE_MINES_MULTIPLIERS).map(([mine, gemsMap]) => [
    Number(mine),
    Object.values(gemsMap),
  ])
);

export function getMinesMultiplierValue(mines: number, gemsOpened: number): number {
  if (gemsOpened <= 0) return 1.0;
  if (STAKE_MINES_MULTIPLIERS[mines]?.[gemsOpened]) {
    return STAKE_MINES_MULTIPLIERS[mines][gemsOpened];
  }
  const list = MINES_MULTIPLIERS_MATRIX[mines];
  if (!list) return 1.0;
  const index = gemsOpened - 1;
  return list[index] ?? (list[list.length - 1] || 1.0);
}

