export interface GameItem {
  name?: string;
  isLive?: boolean;
  id: string;
  title: string;
  slug: string;
  provider: string;
  playersCount: number;
  badge?: string;
  badgeColor?: string;
  href?: string;
  category: "originals" | "live" | "slots" | "game-shows";
  bgGradient?: string;
  isPlayable?: boolean;
  image?: string;
}

export interface ProviderItem {
  id: string;
  name: string;
  slug: string;
  gamesCount: number;
  playersCount: number;
  badge?: string;
  logoBg: string;
  accentColor: string;
}

import { GAME_THUMBNAILS, getGameThumbnail } from "@/data/gameThumbnails";

export function attachThumbnail<T extends GameItem>(game: T): T {
  return {
    ...game,
    image: GAME_THUMBNAILS[game.slug] || GAME_THUMBNAILS[game.id] || game.image,
  };
}

