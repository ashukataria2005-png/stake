export interface GameItem {
  name?: string;
  isLive?: boolean;
  id: string;
  title: string;
  slug: string;
  provider: string;
  playersCount: number;
  livePlayerCount?: number;
  badge?: string;
  badgeColor?: string;
  href?: string;
  category: "originals" | "live" | "slots" | "game-shows" | "Slots" | string;
  bgGradient?: string;
  isPlayable?: boolean;
  image?: string;
  bannerImage?: string;
}

export type StakeGame = GameItem & {
  livePlayerCount?: number;
  bannerImage?: string;
};

export interface ProviderItem {
  id: string;
  name: string;
  slug: string;
  gamesCount: number;
  playersCount: number;
  badge?: string;
  logoBg: string;
  accentColor: string;
}

import { GAME_THUMBNAILS, getGameThumbnail } from "@/data/gameThumbnails";

export function attachThumbnail<T extends GameItem>(game: T): T {
  const img = GAME_THUMBNAILS[game.slug] || GAME_THUMBNAILS[game.id] || game.image;
  return {
    ...game,
    image: img,
    bannerImage: game.bannerImage || img,
    livePlayerCount: game.livePlayerCount ?? game.playersCount,
  };
}

