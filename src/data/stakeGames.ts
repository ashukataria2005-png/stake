export const LIVE_CASINO_GAMES: GameItem[] = (() => {
  const isTrueLiveGame = (g: GameItem) => {
    const cat = (g.category || "").toLowerCase();
    const type = ((g as any).type || "").toLowerCase();
    const prov = (g.provider || "").toLowerCase();

    // Must be from dedicated live dealer providers OR explicitly tagged live
    const isLiveProvider =
      prov === "evolution" ||
      prov === "ezugi" ||
      prov === "mac88" ||
      prov === "pragmatic live" ||
      prov === "pragmatic play live";
    const hasLiveTag =
      g.isLive === true ||
      cat === "live" ||
      cat === "live casino" ||
      type === "live" ||
      type === "live casino";

    if (!isLiveProvider && !hasLiveTag) return false;

    // Strictly exclude slots, crash, burst, or RNG arcade/table games
    const isExcluded =
      cat === "slots" ||
      cat === "burst" ||
      cat === "crash" ||
      cat === "instant" ||
      type === "slot" ||
      type === "slots" ||
      type === "crash" ||
      type === "burst";
    return !isExcluded;
  };

  const evoList = EVOLUTION_GAMES.filter(isTrueLiveGame);
  const ezugiList = EZUGI_GAMES.filter(isTrueLiveGame);
  const mac88List = MAC88_GAMES.filter(isTrueLiveGame);

  const seenIds = new Set<string>([
    ...evoList.map((g) => g.id),
    ...ezugiList.map((g) => g.id),
    ...mac88List.map((g) => g.id),
  ]);
  const otherList = ALL_GAMES.filter((g) => isTrueLiveGame(g) && !seenIds.has(g.id));

  // Round-robin / interleaved sorting:
  // Sequence: 1 Evolution -> 1 Ezugi -> 1 Mac88 / other provider -> Repeat pattern
  const interleaved: GameItem[] = [];
  const addedIds = new Set<string>();

  const addGame = (g?: GameItem) => {
    if (g && !addedIds.has(g.id)) {
      addedIds.add(g.id);
      interleaved.push(g);
    }
  };

  const maxLen = Math.max(evoList.length, ezugiList.length, mac88List.length, otherList.length);
  for (let i = 0; i < maxLen; i++) {
    addGame(evoList[i]);
    addGame(ezugiList[i]);
    if (mac88List[i]) {
      addGame(mac88List[i]);
    } else if (otherList[i]) {
      addGame(otherList[i]);
    }
    if (mac88List[i] && otherList[i]) {
      addGame(otherList[i]);
    }
  }

  return interleaved;
})();

